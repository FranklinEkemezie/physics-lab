/**
 * Optics apparatus.
 *
 * Even though the flagship practical in this build is the simple pendulum,
 * the optics bench is modelled in full so the lab can be extended (and so
 * students can *see* and compare apparatus from different topics).
 */

import * as THREE from 'three';
import { Materials } from '../materials';
import { makeLabelPlane, makeScaleTexture, meshOf, roundedBox } from '../geometry';

/**
 * Ray box: a metal box with a collimating slit that throws one, three or five
 * parallel rays. Used for reflection, refraction and critical-angle work.
 *
 * <b>Anchors:</b> `Aperture` — where the rays leave the box.
 */
export class RayBoxModel {
  readonly group = new THREE.Group();
  #rays: THREE.Mesh[] = [];
  #lamp: THREE.PointLight;
  #on = true;
  #rayCount = 3;

  constructor() {
    this.group.name = 'RayBox';

    const body = meshOf(roundedBox(0.13, 0.075, 0.075, 0.006), Materials.paint('#2f3338', 0.45), 'Body');
    body.rotation.x = -Math.PI / 2;
    body.rotation.z = Math.PI / 2;
    body.position.set(0, 0.038, 0);
    this.group.add(body);

    const well = meshOf(roundedBox(0.11, 0.062, 0.05, 0.004), Materials.paint('#22262a', 0.6), 'Well');
    well.position.set(0, 0.03, 0.032);
    this.group.add(well);

    // Aperture plate with slits at the business end.
    const aperture = meshOf(new THREE.BoxGeometry(0.004, 0.07, 0.07), Materials.paint('#e8e3d6', 0.5), 'AperturePlate');
    aperture.position.set(0.066, 0.038, 0);
    this.group.add(aperture);

    const slit = new THREE.Mesh(
      new THREE.PlaneGeometry(0.05, 0.0016),
      new THREE.MeshBasicMaterial({ color: 0xfff0c0 }),
    );
    slit.rotation.y = Math.PI / 2;
    slit.position.set(0.0685, 0.038, 0);
    slit.name = 'Slit';
    this.group.add(slit);

    // Carry handle.
    const handle = meshOf(new THREE.TorusGeometry(0.026, 0.0035, 8, 24, Math.PI), Materials.chrome(), 'Handle');
    handle.position.set(-0.02, 0.075, 0);
    handle.rotation.y = Math.PI / 2;
    this.group.add(handle);

    // Collimated beams, built as thin translucent boxes.
    const beamMaterial = new THREE.MeshBasicMaterial({
      color: 0xfff2c4,
      transparent: true,
      opacity: 0.33,
      blending: THREE.AdditiveBlending,
      depthWrite: false,
      side: THREE.DoubleSide,
    });
    const beamLength = 0.9;
    for (let i = 0; i < 5; i += 1) {
      const beam = new THREE.Mesh(new THREE.BoxGeometry(beamLength, 0.0022, 0.0022), beamMaterial);
      beam.position.set(0.0685 + beamLength / 2, 0.038 + (i - 2) * 0.014, 0);
      beam.name = `Beam${i}`;
      this.#rays.push(beam);
      this.group.add(beam);
    }
    this.setRayCount(this.#rayCount);

    this.#lamp = new THREE.PointLight(0xffe9b0, 0.7, 1.6, 2);
    this.#lamp.position.set(0.02, 0.038, 0);
    this.group.add(this.#lamp);

    const apertureAnchor = new THREE.Object3D();
    apertureAnchor.name = 'Aperture';
    apertureAnchor.position.set(0.0685, 0.038, 0);
    this.group.add(apertureAnchor);

    this.group.userData.apparatus = { id: 'ray-box', label: 'Ray box' };
    this.group.userData.isHandle = true;
  }

  /** Show 1, 3 or 5 beams. */
  setRayCount(count: number): void {
    this.#rayCount = count;
    const shown: number[] =
      count <= 1 ? [2] : count === 3 ? [1, 2, 3] : [0, 1, 2, 3, 4];
    this.#rays.forEach((beam, index) => {
      beam.visible = this.#on && shown.includes(index);
    });
  }

  setOn(on: boolean): void {
    this.#on = on;
    this.#lamp.intensity = on ? 0.7 : 0;
    this.setRayCount(this.#rayCount);
  }

  get isOn(): boolean {
    return this.#on;
  }

  /** The beams, for experiments that need to raycast against them. */
  get beams(): readonly THREE.Mesh[] {
    return this.#rays;
  }
}

/**
 * Biconvex lens, generated by revolving a spherical-arc profile. The focal
 * length is *derived from the geometry* (lensmaker's equation), not faked.
 *
 * <b>Anchors:</b> `OpticalCentre`.
 */
export class ConvexLensModel {
  readonly group = new THREE.Group();
  readonly focalLengthM: number;
  readonly apertureRadiusM: number;

  /**
   * @param focalLengthM Target focal length in metres.
   * @param apertureRadiusM Lens radius (half the clear diameter).
   */
  constructor(focalLengthM = 0.15, apertureRadiusM = 0.028) {
    this.focalLengthM = focalLengthM;
    this.apertureRadiusM = apertureRadiusM;
    this.group.name = 'ConvexLens';

    const n = 1.49; // acrylic / crown glass
    // Sag needed on each face so that 1/f = (n-1)(1/R1 - 1/R2) with R1 = -R2 = R
    // → R = 2(n-1)f. Each face is a circular arc of radius R.
    const R = 2 * (n - 1) * focalLengthM;
    const r = apertureRadiusM;
    const sag = R - Math.sqrt(Math.max(1e-9, R * R - r * r));

    const profile: THREE.Vector2[] = [];
    const steps = 40;
    for (let i = 0; i <= steps; i += 1) {
      const x = (i / steps) * r;
      profile.push(new THREE.Vector2(x, Math.sqrt(Math.max(0, R * R - x * x)) - Math.sqrt(R * R - r * r) + sag));
    }
    for (let i = steps; i >= 0; i -= 1) {
      const x = (i / steps) * r;
      const y = -(Math.sqrt(Math.max(0, R * R - x * x)) - Math.sqrt(R * R - r * r) + sag);
      profile.push(new THREE.Vector2(x, y));
    }

    const geometry = new THREE.LatheGeometry(profile, 64);
    // LatheGeometry revolves around Y; the lens should lie in the XZ plane
    // with its optical axis along +Z.
    geometry.rotateX(Math.PI / 2);

    const lens = new THREE.Mesh(geometry, Materials.glass());
    lens.name = 'LensBody';
    lens.castShadow = true;
    lens.receiveShadow = true;
    this.group.add(lens);

    const rim = meshOf(new THREE.TorusGeometry(r, 0.0012, 8, 48), Materials.chrome(), 'Rim');
    rim.position.z = 0;
    this.group.add(rim);

    // Lens holder: a ring on a short stalk, so it can stand on the bench.
    const holder = new THREE.Group();
    holder.name = 'Holder';
    const collar = meshOf(new THREE.CylinderGeometry(r * 1.25, r * 1.25, 0.006, 32, 1, true), Materials.aluminium(), 'Collar');
    collar.rotation.x = Math.PI / 2;
    const stalk = meshOf(new THREE.BoxGeometry(0.006, 0.05, 0.006), Materials.aluminium(), 'Stalk');
    stalk.position.set(0, -r * 1.25 - 0.02, 0);
    const foot = meshOf(new THREE.BoxGeometry(0.05, 0.006, 0.03), Materials.aluminium(), 'Foot');
    foot.position.set(0, -r * 1.25 - 0.045, 0);
    holder.add(collar, stalk, foot);
    this.group.add(holder);

    const anchor = new THREE.Object3D();
    anchor.name = 'OpticalCentre';
    anchor.position.set(0, 0, 0);
    this.group.add(anchor);

    this.group.userData.apparatus = { id: 'convex-lens', label: `Convex lens f=${(focalLengthM * 100).toFixed(0)} cm` };
    this.group.userData.optics = { focalLengthM, apertureRadiusM, kind: 'convex-lens' };
  }
}

/**
 * Concave (converging) spherical mirror on a stand.
 *
 * <b>Anchors:</b> `Pole` — the centre of the mirror surface.
 */
export class ConcaveMirrorModel {
  readonly group = new THREE.Group();
  readonly focalLengthM: number;
  readonly radiusOfCurvatureM: number;

  constructor(focalLengthM = 0.15, apertureRadiusM = 0.035) {
    this.focalLengthM = focalLengthM;
    this.radiusOfCurvatureM = focalLengthM * 2;
    this.group.name = 'ConcaveMirror';

    const R = this.radiusOfCurvatureM;
    const r = apertureRadiusM;
    const sag = R - Math.sqrt(Math.max(1e-9, R * R - r * r));

    const profile: THREE.Vector2[] = [];
    const steps = 36;
    for (let i = 0; i <= steps; i += 1) {
      const x = (i / steps) * r;
      const y = -(Math.sqrt(Math.max(0, R * R - x * x)) - Math.sqrt(R * R - r * r) + sag);
      profile.push(new THREE.Vector2(x, y));
    }

    const geometry = new THREE.LatheGeometry(profile, 48);
    geometry.rotateX(Math.PI / 2);
    const mirrorMaterial = Materials.mirror().clone();
    mirrorMaterial.side = THREE.DoubleSide;
    const mirror = new THREE.Mesh(geometry, mirrorMaterial);
    mirror.name = 'MirrorSurface';
    mirror.castShadow = true;
    this.group.add(mirror);

    const rim = meshOf(new THREE.TorusGeometry(r, 0.0015, 8, 48), Materials.castIron(), 'Rim');
    this.group.add(rim);

    const stalk = meshOf(new THREE.CylinderGeometry(0.004, 0.004, 0.05, 12), Materials.chrome(), 'Stalk');
    stalk.position.y = -r - 0.026;
    const base = meshOf(new THREE.CylinderGeometry(0.03, 0.034, 0.008, 28), Materials.castIron(), 'Base');
    base.position.y = -r - 0.05;
    this.group.add(stalk, base);

    const pole = new THREE.Object3D();
    pole.name = 'Pole';
    this.group.add(pole);

    this.group.userData.apparatus = { id: 'concave-mirror', label: 'Concave mirror' };
    this.group.userData.optics = { focalLengthM, radiusOfCurvatureM: R, kind: 'concave-mirror' };
  }
}

/**
 * Rectangular glass block for refraction experiments.
 * Filled with the real refractive index so Snell's law can be applied.
 *
 * <b>Anchors:</b> `FaceFront`, `FaceBack`.
 */
export function buildGlassBlock(options: { lengthM?: number; widthM?: number; heightM?: number; refractiveIndex?: number } = {}): THREE.Group {
  const { lengthM = 0.1, widthM = 0.06, heightM = 0.02, refractiveIndex = 1.5 } = options;
  const group = new THREE.Group();
  group.name = 'GlassBlock';

  const material = Materials.acrylic().clone();
  material.thickness = Math.min(lengthM, widthM);
  if ('ior' in material) (material as THREE.MeshPhysicalMaterial).ior = refractiveIndex;

  const block = meshOf(new THREE.BoxGeometry(lengthM, heightM, widthM), material, 'BlockBody');
  block.position.y = heightM / 2;
  group.add(block);

  const front = new THREE.Object3D();
  front.name = 'FaceFront';
  front.position.set(0, heightM / 2, widthM / 2);
  const back = new THREE.Object3D();
  back.name = 'FaceBack';
  back.position.set(0, heightM / 2, -widthM / 2);
  group.add(front, back);

  group.userData.apparatus = { id: 'glass-block', label: `Glass block (n = ${refractiveIndex.toFixed(2)})` };
  group.userData.optics = { refractiveIndex, lengthM, widthM, heightM, kind: 'glass-block' };
  group.userData.isHandle = true;
  return group;
}

/**
 * White screen with a millimetre grid, for image work and diffraction.
 * Sits on a stand so its height can be adjusted.
 */
export function buildScreen(options: { widthM?: number; heightM?: number } = {}): THREE.Group {
  const { widthM = 0.12, heightM = 0.1 } = options;
  const group = new THREE.Group();
  group.name = 'Screen';

  const board = meshOf(roundedBox(widthM, heightM, 0.005, 0.004), Materials.screen(), 'Board');
  board.position.y = heightM / 2 + 0.03;
  group.add(board);

  const grid = new THREE.Mesh(
    new THREE.PlaneGeometry(widthM * 0.94, heightM * 0.94),
    new THREE.MeshBasicMaterial({
      map: makeScaleTexture({
        spanMm: 100,
        pixelsPerMm: 8,
        heightPx: 64,
        majorEveryMm: 10,
        minorPerMajor: 2,
        background: '#fbfbf6',
        ink: 'rgba(60,60,60,0.5)',
        numbers: false,
        repeat: 1,
      }),
      transparent: true,
      opacity: 0.5,
    }),
  );
  grid.name = 'ScaleGrid';
  grid.position.set(0, heightM / 2 + 0.03, 0.0028);
  group.add(grid);

  const stalk = meshOf(new THREE.BoxGeometry(0.008, 0.03, 0.008), Materials.aluminium(), 'Stalk');
  stalk.position.y = 0.015;
  const foot = meshOf(new THREE.BoxGeometry(0.07, 0.006, 0.04), Materials.aluminium(), 'Foot');
  foot.position.y = 0.003;
  group.add(stalk, foot);

  const centre = new THREE.Object3D();
  centre.name = 'ScreenCentre';
  centre.position.set(0, heightM / 2 + 0.03, 0.0028);
  group.add(centre);

  group.userData.isHandle = true;
  group.userData.apparatus = { id: 'screen', label: 'White screen' };
  return group;
}

/**
 * Optical bench: a graduated rail with sliding carriers. The scale is real
 * (centimetre graduations) so students can read object and image distances.
 */
export class OpticalBenchModel {
  readonly group = new THREE.Group();
  readonly lengthM: number;

  constructor(lengthM = 1) {
    this.lengthM = lengthM;
    this.group.name = 'OpticalBench';

    const railHeight = 0.014;
    const rail = meshOf(new THREE.BoxGeometry(lengthM, 0.012, 0.055), Materials.aluminium(), 'Rail');
    rail.position.y = railHeight;
    this.group.add(rail);

    // Graduated strip on the front face of the rail.
    const scale = new THREE.Mesh(
      new THREE.PlaneGeometry(lengthM * 0.99, 0.038),
      new THREE.MeshStandardMaterial({
        map: makeScaleTexture({
          spanMm: lengthM * 1000,
          pixelsPerMm: Math.min(3, 2000 / (lengthM * 1000)),
          heightPx: 96,
          majorEveryMm: 10,
          minorPerMajor: 10,
          numbers: true,
          background: '#e9e5da',
        }),
        roughness: 0.8,
      }),
    );
    scale.name = 'RailScale';
    scale.position.set(0, railHeight, 0.0276);
    this.group.add(scale);

    // End stops.
    for (const x of [-lengthM / 2, lengthM / 2]) {
      const stop = meshOf(new THREE.BoxGeometry(0.012, 0.026, 0.06), Materials.aluminium(), 'EndStop');
      stop.position.set(x, railHeight + 0.006, 0);
      this.group.add(stop);
    }

    for (const x of [-lengthM / 2 + 0.1, 0, lengthM / 2 - 0.1]) {
      const foot = meshOf(new THREE.BoxGeometry(0.05, 0.008, 0.075), Materials.castIron(), 'Foot');
      foot.position.set(x, 0.004, 0);
      this.group.add(foot);
    }

    this.group.userData.apparatus = { id: 'optical-bench', label: `Optical bench (${lengthM * 100} cm)` };
    this.group.userData.scale = {
      orientation: 'horizontal',
      spanMm: lengthM * 1000,
      zeroOffsetM: -lengthM / 2,
      scaleFaceNormal: new THREE.Vector3(0, 0, 1),
      scaleFaceCentre: new THREE.Vector3(0, railHeight, 0.028),
      faceThicknessM: 0.055,
      label: 'OPTICAL BENCH',
    };
  }

  /** A slider carrying any object along the rail. */
  makeCarrier(object: THREE.Object3D): THREE.Group {
    const carrier = new THREE.Group();
    carrier.name = 'Carrier';
    const saddle = meshOf(new THREE.BoxGeometry(0.03, 0.012, 0.062), Materials.aluminium(), 'Saddle');
    saddle.position.y = 0.028;
    const post = meshOf(new THREE.CylinderGeometry(0.004, 0.004, 0.03, 12), Materials.chrome(), 'Post');
    post.position.y = 0.046;
    carrier.add(saddle, post);
    object.position.y = 0.06;
    carrier.add(object);
    return carrier;
  }
}

/**
 * Plane mirror on a wooden block — the workhorse of reflection experiments.
 *
 * <b>Anchors:</b> `MirrorPlane` — the reflecting surface itself.
 */
export function buildPlaneMirror(options: { widthM?: number; heightM?: number } = {}): THREE.Group {
  const { widthM = 0.09, heightM = 0.06 } = options;
  const group = new THREE.Group();
  group.name = 'PlaneMirror';

  const backing = meshOf(new THREE.BoxGeometry(widthM, heightM, 0.004), Materials.paint('#3a3f45', 0.6), 'Backing');
  backing.position.y = heightM / 2 + 0.012;
  group.add(backing);

  const mirror = meshOf(new THREE.BoxGeometry(widthM * 0.985, heightM * 0.985, 0.0008), Materials.mirror(), 'MirrorSurface');
  mirror.position.set(0, heightM / 2 + 0.012, 0.0025);
  group.add(mirror);

  const block = meshOf(roundedBox(widthM * 0.6, 0.024, 0.03, 0.003), Materials.darkWood(), 'Block');
  block.position.y = 0.012;
  group.add(block);

  const plane = new THREE.Object3D();
  plane.name = 'MirrorPlane';
  plane.position.set(0, heightM / 2 + 0.012, 0.003);
  group.add(plane);

  group.userData.isHandle = true;
  group.userData.apparatus = { id: 'plane-mirror', label: 'Plane mirror' };
  return group;
}

/**
 * Equilateral glass prism for refraction and dispersion work.
 * The apex angle is exactly 60°, so minimum-deviation calculations work.
 */
export function buildPrism(options: { sideM?: number; refractiveIndex?: number } = {}): THREE.Group {
  const { sideM = 0.05, refractiveIndex = 1.52 } = options;
  const group = new THREE.Group();
  group.name = 'Prism';

  const shape = new THREE.Shape();
  const height = (Math.sqrt(3) / 2) * sideM;
  shape.moveTo(-sideM / 2, 0);
  shape.lineTo(sideM / 2, 0);
  shape.lineTo(0, height);
  shape.closePath();

  const geometry = new THREE.ExtrudeGeometry(shape, { depth: 0.035, bevelEnabled: false, curveSegments: 1 });
  geometry.translate(0, 0.035, 0);
  geometry.rotateX(-Math.PI / 2);

  const material = Materials.acrylic().clone();
  if ('ior' in material) (material as THREE.MeshPhysicalMaterial).ior = refractiveIndex;

  const body = new THREE.Mesh(geometry, material);
  body.name = 'PrismBody';
  body.castShadow = true;
  body.receiveShadow = true;
  group.add(body);

  const apex = new THREE.Object3D();
  apex.name = 'Apex';
  apex.position.set(0, height, 0);
  group.add(apex);

  group.userData.isHandle = true;
  group.userData.apparatus = { id: 'prism', label: 'Glass prism' };
  group.userData.optics = { refractiveIndex, apexAngleDeg: 60, kind: 'prism' };
  return group;
}

/** A protractor for measuring angles of incidence and refraction. */export function buildProtractor(radiusM = 0.05): THREE.Group {
  const group = new THREE.Group();
  group.name = 'Protractor';

  const shape = new THREE.Shape();
  shape.absarc(0, 0, radiusM, 0, Math.PI, false);
  shape.lineTo(-radiusM, 0);
  shape.absarc(0, 0, radiusM * 0.94, Math.PI, 0, true);
  shape.closePath();

  const geometry = new THREE.ExtrudeGeometry(shape, { depth: 0.0015, bevelEnabled: false });
  const body = new THREE.Mesh(geometry, Materials.acrylic().clone());
  body.rotation.x = -Math.PI / 2;
  body.name = 'ProtractorBody';
  group.add(body);

  for (let degrees = 0; degrees <= 180; degrees += 10) {
    const angle = THREE.MathUtils.degToRad(degrees);
    const isMajor = degrees % 10 === 0;
    const tick = meshOf(
      new THREE.BoxGeometry(0.0004, 0.0015, isMajor ? radiusM * 0.12 : radiusM * 0.07),
      Materials.blackSteel(),
      'Tick',
    );
    tick.position.set(Math.cos(angle) * radiusM * 0.92, 0.001, Math.sin(angle) * radiusM * 0.92);
    tick.rotation.y = -angle;
    tick.castShadow = false;
    group.add(tick);
  }

  const label = makeLabelPlane({
    text: '0 – 180°',
    widthM: radiusM * 0.9,
    fontScale: 0.16,
    foreground: '#333',
  });
  label.rotation.x = -Math.PI / 2;
  label.position.set(0, 0.0028, radiusM * 0.35);
  group.add(label);

  group.userData.apparatus = { id: 'protractor', label: 'Protractor' };
  group.userData.isHandle = true;
  return group;
}
